/** 兜底指导：不编造模块专属框架，只给出通用工作方式。 */
const FALLBACK_PLAYBOOK = [
  '关注点：先把现象、时间线、涉及对象与教师已尝试的做法问清。',
  '常见误区：在信息不足时下结论；把通用建议说成平台规定或制度要求。',
  '建议动作路径：先给当下可执行的动作 → 需要确定性结论时建议进入对应模块完成量表。'
].join('\n')

/** 取某模块的静态专业指导；未知模块返回通用兜底文本，不抛错。 */
export function getModulePlaybook(module: ModuleId | string | null | undefined): string {
  if (!module || typeof module !== 'string') return FALLBACK_PLAYBOOK
  return PLAYBOOKS[module as ModuleId] || FALLBACK_PLAYBOOK
}

/** 五个模块的指导文本都带上这句共同边界，避免模型把框架当成结论。 */
export const PLAYBOOK_BOUNDARY = '以上仅作为分析与行动框架；量表结论、等级、归因与风险判断一律以模块内确定性规则的结果为准。'

/** 完整的指导文本（含边界声明），供工具返回值直接使用。 */
export function getModulePlaybookText(module: ModuleId | string | null | undefined): string {
  return `${getModulePlaybook(module)}\n${PLAYBOOK_BOUNDARY}`
}
